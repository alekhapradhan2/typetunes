// ─── Word Generation ──────────────────────────────────────────────────────────

function randomFrom<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

function injectPunctuation(words: string[]): string[] {
  return words.map((word, i) => {
    if (i === words.length - 1) return word + '.';
    if (Math.random() < 0.12) return word + randomFrom(PUNCTUATION);
    return word;
  });
}

function injectNumbers(words: string[]): string[] {
  return words.map((word) => {
    if (Math.random() < 0.08) return randomFrom(NUMBER_TOKENS);
    return word;
  });
}

export interface GenerateOptions {
  count: number;
  includePunctuation?: boolean;
  includeNumbers?: boolean;
}

export function generateWordList(opts: GenerateOptions): string[] {
  let words: string[] = [];
  while (words.length < opts.count) {
    words.push(randomFrom(COMMON_WORDS));
  }
  words = words.slice(0, opts.count);
  if (opts.includeNumbers) words = injectNumbers(words);
  if (opts.includePunctuation) words = injectPunctuation(words);
  return words;
}

export function generateTestText(opts: GenerateOptions): string {
  return generateWordList(opts).join(' ');
}

export function getRandomQuote(): string {
  return randomFrom(QUOTES);
}

export function getRandomPassage(difficulty: 'short' | 'medium' | 'long' = 'medium'): string {
  const count = difficulty === 'short' ? 25 : difficulty === 'long' ? 60 : 40;
  return generateTestText({ count, includePunctuation: true });
}
